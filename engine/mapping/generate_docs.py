"""
Reads field_mapping.json and generates docs/mapping.md.
Run any time the JSON is updated: python mapping/generate_docs.py
"""

import json
from pathlib import Path

MAPPING_FILE = Path(__file__).parent / "field_mapping.json"
OUTPUT_FILE  = Path(__file__).parent.parent / "docs" / "mapping.md"

CONFIDENCE_LABEL = {
    (0.9, 1.01): "High",
    (0.7, 0.9):  "Review",
    (0.0, 0.7):  "Verify",
}

def confidence_label(score: float) -> str:
    for (low, high), label in CONFIDENCE_LABEL.items():
        if low <= score < high:
            return label
    return "Unknown"

def confidence_badge(score: float) -> str:
    label = confidence_label(score)
    icons = {"High": "🟢", "Review": "🟡", "Verify": "🔴"}
    return f"{icons.get(label, '')} {score:.2f}"


def build_markdown(data: dict) -> str:
    meta   = data["_meta"]
    tables = data["tables"]

    lines = [
        "# Field Mapping Reference",
        "",
        f"> **Source:** {meta['source_system']}  ",
        f"> **Target:** {meta['target_system']}  ",
        f"> **Generated by:** {meta['generated_by']}  ",
        f"> **Version:** {meta['version']}",
        "",
        f"> {meta['notes']}",
        "",
        "---",
        "",
    ]

    # Group tables by domain
    domains: dict[str, list] = {}
    for table_name, table in tables.items():
        domain = table.get("domain", "Other")
        domains.setdefault(domain, []).append((table_name, table))

    # Table of contents
    lines.append("## Contents\n")
    for domain in domains:
        anchor = domain.lower().replace(" ", "-")
        lines.append(f"- [{domain}](#{anchor})")
    lines.append("")
    lines.append("---")
    lines.append("")

    for domain, entries in domains.items():
        lines.append(f"## {domain}")
        lines.append("")

        for table_name, table in entries:
            target = table["target_table"]
            desc   = table.get("description", "")

            lines.append(f"### `{table_name}` → `{target}`")
            lines.append("")
            if desc:
                lines.append(f"_{desc}_")
                lines.append("")

            lines.append("| Source Column | Target Column | Transform | Confidence | Notes |")
            lines.append("|---|---|---|---|---|")

            for col in table["columns"]:
                badge = confidence_badge(col["confidence"])
                notes = col.get("notes", "")
                lines.append(
                    f"| `{col['source']}` | `{col['target']}` "
                    f"| `{col['transform']}` | {badge} | {notes} |"
                )

            lines.append("")

        lines.append("---")
        lines.append("")

    return "\n".join(lines)


def main():
    with open(MAPPING_FILE) as f:
        data = json.load(f)

    md = build_markdown(data)

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(md, encoding="utf-8")
    print(f"Generated: {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
